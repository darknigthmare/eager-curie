#!/usr/bin/env node
'use strict';
// Bake measured, validated authoring output; never call a generation service.
// First run qa-level-coherence --author-layout --output=.tools/<new>.json.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const input=process.argv.find(arg=>arg.startsWith('--input='))?.slice(8);
if(!input)throw Error('Use --input=.tools/<validated-author-layout>.json, then --check or --write');
const source=path.resolve(root,input);
assert(source.startsWith(path.join(root,'.tools')+path.sep),'Authoring input must be private local QA evidence');
const report=JSON.parse(fs.readFileSync(source,'utf8'));
assert(report.groups>0&&report.passed===report.groups,'Refuse to bake an unvalidated layout');
assert.equal(report.placements?.length,300);
assert.equal(new Set(report.placements.map(prop=>prop.id)).size,300);
assert(report.placements.every(prop=>prop.status==='placed'&&prop.route?.length&&prop.accessOrigin&&prop.localBounds));
const round=n=>{assert(Number.isFinite(n));return Number(n.toFixed(6));};
const point=p=>({x:round(p.x),z:round(p.z)});
const compress=route=>{
  if(route.length<3)return route.map(point);
  const result=[point(route[0])];
  for(let i=1;i<route.length-1;i++){
    const a=route[i-1],b=route[i],c=route[i+1];
    if(Math.abs((b.x-a.x)*(c.z-b.z)-(b.z-a.z)*(c.x-b.x))>1e-6)result.push(point(b));
  }
  result.push(point(route.at(-1)));return result;
};
const records=report.placements.map(prop=>({id:prop.id,factory:prop.factory,x:round(prop.x),z:round(prop.z),
  sector:prop.sector,preferredSector:prop.preferredSector,minStage:prop.minStage,
  localBounds:Object.fromEntries(Object.entries(prop.localBounds).map(([key,value])=>[key,round(value)])),
  accessOrigin:point(prop.accessOrigin),interactionPoint:point(prop.interactionPoint),route:compress(prop.route)}));
const anchors=report.recoveryRoomAnchors.map(anchor=>({id:anchor.id,sector:anchor.sector,...point(anchor)}));
const legacy=report.legacyRelocations||[];
const body='/* Generated by tools/generate-industrial-layout.cjs from real factory bounds.\n'+
  ' * Stable IDs, 2-unit adult clearance, authored station sectors; not film metrology.\n'+
  ' * Regenerate only after qa-level-coherence --author-layout succeeds. */\n'+
  '(function (global) {\n  \'use strict\';\n  const records = [\n'+records.map(record=>'    '+JSON.stringify(record)).join(',\n')+
  '\n  ];\n  global.HiveIndustrialLayout = Object.freeze({\n    schema: \'hive-industrial-layout-v1\', version: 1, clearance: 2, boundary: 73.4,\n'+
  '    anchors: Object.freeze('+JSON.stringify(anchors)+'),\n'+
  '    legacyRelocations: Object.freeze('+JSON.stringify(legacy)+'),\n'+
  '    records: Object.freeze(records.map(record => Object.freeze(record)))\n  });\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
const target=path.join(root,'src/industrial-layout.js');
if(process.argv.includes('--check')){
  assert.equal(fs.readFileSync(target,'utf8'),body,'Compiled layout differs from validated geometry/route output');
  console.log('Industrial layout byte-exact:300 records, '+anchors.length+' room anchors');
}else if(process.argv.includes('--write')){
  fs.writeFileSync(target,body);
  console.log('Wrote src/industrial-layout.js:300 validated placements');
}else process.stdout.write(body);
